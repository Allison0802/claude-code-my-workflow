# scaffold.R — generates a per-run driver R script parameterized by slot.kind.
# Driver script is written to cfg$paths$out_dir or a user-specified dest.
# It's responsible for materializing a variant (from cli args or env vars) into
# the payload shape expected by the evaluator, then invoking the evaluator.

#' Generate a driver script parameterized by slot.kind.
#'
#' @param cfg parsed+validated config (yaml::read_yaml output).
#' @param out_path path to write driver script.
#' @return invisible path written.
scaffold_driver <- function(cfg, out_path) {
  kind <- cfg$slot$kind
  ser <- switch(kind,
    feature_set     = "list(feature_set_expr = jsonlite::fromJSON(var_json))",
    hyperparameters = "list(hyperparameters = jsonlite::fromJSON(var_json, simplifyVector = FALSE))",
    formula         = "list(formula_str = var_json)",
    me_stop("scaffold_driver: unknown slot.kind '%s'", kind)
  )
  target_script <- cfg$target_script
  results_pattern <- cfg$evaluator$results_file_pattern %||% "results.rds"

  tmpl <- sprintf('#!/usr/bin/env Rscript
# Auto-generated by method-evolve scaffold_driver() — DO NOT EDIT BY HAND.
# Slot kind: %s
# Target evaluator: %s

suppressPackageStartupMessages({ library(jsonlite); library(here) })

env <- function(k, default = NULL) {
  v <- Sys.getenv(k, unset = NA)
  if (is.na(v) || !nzchar(v)) default else v
}

variant_id <- env("VARIANT_ID", "var_00000")
var_json   <- env("VARIANT_JSON", "")
if (!nzchar(var_json)) {
  var_path <- env("VARIANT_PATH", "")
  if (!nzchar(var_path)) stop("VARIANT_JSON or VARIANT_PATH env var required")
  var_json <- paste(readLines(var_path, warn = FALSE), collapse = "\\n")
}

payload <- %s
variant_rds <- tempfile(fileext = ".rds")
saveRDS(payload, variant_rds)
Sys.setenv(VARIANT_FILE = variant_rds)

source("%s")
', kind, target_script, ser, target_script)

  dir.create(dirname(out_path), recursive = TRUE, showWarnings = FALSE)
  writeLines(tmpl, out_path)
  Sys.chmod(out_path, mode = "0755")
  invisible(out_path)
}

#' Convenience wrapper: scaffold_run(cfg) computes the driver path from
#' cfg$paths$out_dir and writes to out_dir/driver.R.
scaffold_run <- function(cfg, out_dir = NULL) {
  od <- out_dir %||% cfg$paths$out_dir %||% me_stop("no out_dir available")
  out_path <- file.path(od, "driver.R")
  scaffold_driver(cfg, out_path)
}
